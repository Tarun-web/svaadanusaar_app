package com.dietapp.diet_app.health_profile.NutritionTarget.dto.response;

import com.dietapp.diet_app.health_profile.NutritionTarget.enums.CalorieSafetyStatus;

import java.math.BigDecimal;
import java.util.List;

/**
 * The output of {@code CarbohydrateCalculator}.
 *
 * <h3>Central formula</h3>
 * <pre>
 *   carbohydrateCalories  = FatCalculationResult.remainingCaloriesForCarbs()
 *                           (clamped to 0 when negative)
 *   carbohydrateGrams     = carbohydrateCalories / 4
 * </pre>
 *
 * <h3>Negative headroom</h3>
 * <p>When the upstream {@code FatCalculationResult} already signals
 * infeasibility ({@code remainingCaloriesForCarbs &le; 0}),
 * {@link #carbohydrateGrams} will be {@code 0} and
 * {@link #feasible} will be {@code false}.
 * Carbohydrates are never negative.</p>
 *
 * <h3>Safety status</h3>
 * <p>The {@link #safetyStatus} is never less severe than the upstream
 * fat-layer safety status — it can only stay the same or become worse.</p>
 *
 * <h3>Protein and fat are never modified</h3>
 * <p>This result carries only the carbohydrate allocation.
 * Upstream values are not changed here.</p>
 */
public record CarbohydrateCalculationResult(

        /**
         * The daily carbohydrate target in grams.
         *
         * <p>Always &ge; 0. Clamped to zero when remaining calories
         * are negative or zero.</p>
         */
        BigDecimal carbohydrateGrams,

        /**
         * The calories allocated to carbohydrates.
         *
         * <p>Equals {@link #remainingCaloriesFromUpstream} when positive,
         * otherwise {@code 0}.</p>
         */
        BigDecimal carbohydrateCalories,

        /**
         * The raw remaining-calories value received from the upstream
         * {@code FatCalculationResult}.
         *
         * <p>May be negative when the macro combination is infeasible.
         * Preserved here for traceability — the orchestration layer can
         * inspect this to understand why carbohydrates are zero.</p>
         */
        BigDecimal remainingCaloriesFromUpstream,

        /**
         * Whether the carbohydrate allocation is usable for a normal diet plan.
         *
         * <p>{@code false} when {@link #remainingCaloriesFromUpstream} is
         * &le; 0 (no calories available for carbohydrates).</p>
         */
        boolean feasible,

        /**
         * Overall safety status.
         *
         * <p>Never less severe than the upstream fat-layer safety status.
         * Uses the same {@link CalorieSafetyStatus} taxonomy as the rest
         * of the macro pipeline.</p>
         */
        CalorieSafetyStatus safetyStatus,

        /**
         * Whether clinical review is required.
         *
         * <p>Propagated from the upstream {@code FatCalculationResult} —
         * never overridden to {@code false} downstream.</p>
         */
        boolean requiresClinicalReview,

        /**
         * Warnings generated by {@code CarbohydrateCalculator}.
         *
         * <p>Covers zero headroom, upstream infeasibility propagation,
         * and upstream clinical-review propagation.
         * Upstream fat warnings are NOT copied here — they remain in
         * {@code FatCalculationResult} and are aggregated at the
         * orchestration layer.</p>
         */
        List<CarbohydrateWarning> warnings

) {
}
